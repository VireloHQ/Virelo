import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createVireloServer } from '../dist/server.js';

const repo=fileURLToPath(new URL('../',import.meta.url));
const {chromium}=createRequire(process.env.VIRELO_TEST_NODE_PACKAGE||join(repo,'package.json'))('playwright');
const root=await mkdtemp(join(tmpdir(),'virelo-command-ui-'));
const screenshots=join(repo,'node_modules','.cache');await mkdir(screenshots,{recursive:true});
process.env.VIRELO_LOG_LEVEL='silent';
let browser,server,page;
try{
  server=await createVireloServer({dataDir:root,mediaPaths:[],host:'127.0.0.1',port:0});
  server.db.updateSettings({libraryWatchEnabled:false,externalMetadataEnabled:false});
  await server.app.listen({host:'127.0.0.1',port:0});const base='http://127.0.0.1:'+server.app.server.address().port;
  browser=await chromium.launch({headless:true,executablePath:process.env.VIRELO_TEST_CHROMIUM});
  const context=await browser.newContext({viewport:{width:1440,height:1000},serviceWorkers:'block',reducedMotion:'reduce',permissions:['clipboard-read','clipboard-write']});
  const api=(method,path,data)=>context.request.fetch(base+path,{method,headers:{'X-Virelo-Request':'1'},data});
  const setup=await api('POST','/api/auth/setup',{username:'owner',password:'1234'});assert.equal(setup.status(),200,await setup.text());
  page=await context.newPage();page.setDefaultTimeout(15000);
  const errors=[],outside=[];page.on('pageerror',error=>errors.push(error.message));page.on('request',request=>{if(new URL(request.url()).origin!==base)outside.push(request.url());});
  await page.goto(base+'/settings#commands');
  await page.getByRole('heading',{name:'External tools',exact:true}).waitFor();
  await page.getByRole('button',{name:'Add command',exact:true}).click();
  await page.getByLabel('Button name',{exact:true}).fill('Local test launcher');
  await page.getByLabel('Executable',{exact:true}).fill(process.execPath);
  await page.getByLabel('Arguments',{exact:true}).fill([join(repo,'tests','fixtures','custom-command.mjs'),'hold','{url}'].join('\n'));
  await page.getByLabel('Generated URL domain',{exact:true}).fill('share.example');
  await page.getByRole('button',{name:'Save command',exact:true}).click();
  await page.getByRole('heading',{name:'Local test launcher',exact:true}).waitFor();
  assert.equal((await(await api('GET','/api/commands')).json())[0].status,'stopped','saving does not execute');
  await page.getByRole('button',{name:'Start',exact:true}).click();
  await page.getByRole('link',{name:'https://ready.share.example',exact:true}).waitFor();
  await page.getByRole('button',{name:'Copy URL',exact:true}).click();
  await page.getByText('URL copied',{exact:true}).waitFor();
  await page.getByText('Command output',{exact:true}).click();
  assert.ok((await page.getByLabel('Local test launcher output').innerText()).includes(base),'{url} uses the actual random port');
  const edit=page.getByRole('button',{name:'Edit',exact:true});assert.equal(await edit.isDisabled(),true);
  await page.screenshot({path:join(screenshots,'commands-desktop.png')});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.getByRole('button',{name:'Stop',exact:true}).isVisible());
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'no mobile horizontal overflow');
  await page.screenshot({path:join(screenshots,'commands-mobile.png')});
  await page.getByRole('button',{name:'Stop',exact:true}).click();
  await page.getByText('Stopped',{exact:true}).waitFor();
  await page.reload();await page.getByText('Stopped',{exact:true}).waitFor();
  assert.equal((await(await api('GET','/api/commands')).json())[0].status,'stopped','reload does not execute');
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'command editor fits mobile');
  await page.screenshot({path:join(screenshots,'commands-mobile-editor.png'),fullPage:true});
  const input=page.getByLabel('Button name',{exact:true});await input.click();
  assert.equal(await input.evaluate(e=>getComputedStyle(e).boxShadow),'none','no double focus ring');
  await page.getByLabel('Executable',{exact:true}).fill(join(root,'missing-executable'));
  await page.getByRole('button',{name:'Save command',exact:true}).click();
  await page.getByRole('button',{name:'Start',exact:true}).click();
  await page.getByText('Failed',{exact:true}).waitFor();
  await page.getByRole('alert').filter({hasText:'Could not start'}).waitFor();
  await page.getByText('Command output',{exact:true}).click();
  assert.match(await page.getByLabel('Local test launcher output').innerText(),/ENOENT/);
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  await page.getByRole('button',{name:'Remove command',exact:true}).click();
  const dialog=page.getByRole('alertdialog');await dialog.waitFor();await dialog.getByRole('button',{name:'Remove command',exact:true}).click();
  await dialog.waitFor({state:'hidden'});await page.getByRole('button',{name:'Add command',exact:true}).waitFor();
  assert.deepEqual(await(await api('GET','/api/commands')).json(),[]);
  const proxy=await browser.newContext({serviceWorkers:'block',extraHTTPHeaders:{'X-Forwarded-For':'203.0.113.9'}});
  const login=await proxy.request.post(base+'/api/auth/login',{headers:{'X-Virelo-Request':'1'},data:{username:'owner',password:'1234'}});assert.equal(login.status(),200);
  const remotePage=await proxy.newPage(),commandRequests=[];remotePage.on('request',request=>{if(request.url().includes('/api/commands'))commandRequests.push(request.url());});
  await remotePage.goto(base+'/settings#commands');await remotePage.getByRole('heading',{name:'Settings',exact:true}).waitFor();
  assert.equal(await remotePage.locator('.settings-sidebar').getByRole('button',{name:'External tools',exact:true}).count(),0);
  assert.deepEqual(commandRequests,[]);assert.deepEqual(outside,[]);assert.deepEqual(errors,[]);
  console.log('PASS custom commands: desktop/mobile CRUD, explicit start/stop, scoped URL, copy, random-port placeholder, failure output, focus, remote UI isolation and no external requests');
}catch(error){if(page)await page.screenshot({path:join(screenshots,'commands-failure.png')}).catch(()=>{});throw error;}
finally{await browser?.close();await server?.app.close();await rm(root,{recursive:true,force:true});}
