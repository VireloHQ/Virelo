import { join } from 'node:path';
import { openPlaybackSetting } from './playback-settings.mjs';

export async function auditPlayerTransport(page,label,check,artifacts) {
  const player=page.locator('.player:not(.short-player)'),video=player.locator('video');
  if(await video.evaluate(element=>!element.paused))await player.getByRole('button',{name:'Pause',exact:true}).click();
  await player.focus();
  const compact=await page.evaluate(()=>matchMedia('(max-width:650px), (max-width:1000px) and (max-height:500px)').matches);
  const transport=player.getByRole('group',{name:'Playback controls'});
  const names=await transport.getByRole('button').evaluateAll(buttons=>buttons.map(button=>button.getAttribute('aria-label')));
  check(JSON.stringify(names)===JSON.stringify(compact?['Rewind 10 seconds','Play','Fast-forward 30 seconds']:['Shuffle queue','Previous video','Rewind 10 seconds','Play','Fast-forward 30 seconds','Next video','Repeat']),label+' transport retains the appropriate action order without mobile duplicates');
  check(await transport.getByRole('button').evaluateAll(buttons=>buttons.every(button=>{const box=button.getBoundingClientRect();return box.width>=40&&box.height>=44;})),label+' transport touch targets remain usable');
  check(await player.locator('.player-title').textContent()===await video.evaluate(element=>element.closest('.player').getAttribute('aria-label').replace(/ player$/,'')),label+' title appears inside the controls');
  check(await player.locator('.player-toolbar').evaluate(element=>element.scrollWidth<=element.clientWidth)&&await transport.evaluate(element=>element.scrollWidth<=element.clientWidth),label+' toolbar and transport do not overflow');
  const geometry=await player.locator('.player-controls').boundingBox(),viewport=page.viewportSize();
  if(compact){
    const layout=await player.evaluate(element=>{
      const rect=element.getBoundingClientRect(),timeline=element.querySelector('.player-timeline').getBoundingClientRect(),transport=element.querySelector('.player-transport').getBoundingClientRect(),tools=element.querySelector('.player-tools').getBoundingClientRect(),controls=element.querySelector('.player-controls'),style=getComputedStyle(controls);
      const dock=document.querySelector('.mobile-nav')?.getBoundingClientRect();
      return {seekHeight:timeline.height,seekBottom:rect.bottom-timeline.bottom,center:Math.abs((transport.top+transport.bottom)/2-(rect.top+rect.bottom)/2),toolsAbove:tools.bottom<=transport.top,seekBelow:timeline.top>=transport.bottom,blur:style.backdropFilter,hitThrough:style.pointerEvents==='none',titleHidden:getComputedStyle(element.querySelector('.player-title-block')).display==='none',fits:rect.top>=0&&rect.bottom<=Math.min(innerHeight,dock?.height?dock.top:innerHeight)};
    });
    check(layout.seekHeight===44&&Math.abs(layout.seekBottom)<1,label+' only a 44px seek strip remains at the bottom');
    check(layout.center<1&&layout.toolsAbove&&layout.seekBelow,label+' mobile tools, centered playback and seek strip never overlap');
    check(layout.fits,label+' mobile video and seek strip fit above the navigation dock, including landscape');
    check(layout.blur==='none'&&layout.hitThrough&&layout.titleHidden,label+' mobile video has no thick blurred panel or duplicate title and empty areas stay tappable');
    check(await player.getByRole('slider',{name:'Seek',exact:true}).evaluate(element=>element.getBoundingClientRect().height>=44),label+' mobile seek retains a 44px touch target');
    check(await player.locator('.player-tools').getByRole('button').evaluateAll(buttons=>buttons.every(button=>{const box=button.getBoundingClientRect();return box.width>=44&&box.height>=44;})),label+' mobile auxiliary tools retain 44px touch targets');
    await openPlaybackSetting(page,'Subtitles');
    await page.getByRole('menuitemradio',{name:/^English/}).click();
    await player.locator('.player-caption').waitFor();
    check(await player.evaluate(element=>{const caption=element.querySelector('.player-caption').getBoundingClientRect(),timeline=element.querySelector('.player-timeline').getBoundingClientRect();return caption.top>=element.getBoundingClientRect().top&&caption.bottom<=timeline.top;}),label+' mobile subtitles remain above the seek strip instead of being pushed outside the video');
    await openPlaybackSetting(page,'Subtitles');
    await page.getByRole('menuitemradio',{name:'Off',exact:true}).click();
    await player.getByRole('button',{name:'Fullscreen',exact:true}).click();
    await page.waitForFunction(()=>Boolean(document.fullscreenElement));
    check(await player.locator('.player-title').isVisible(),label+' fullscreen retains a visible title');
    await page.evaluate(()=>document.exitFullscreen());
    await page.waitForTimeout(350);
  }else check(geometry.height<=(viewport.width>1000?112:140),label+' desktop control panel keeps a compact height');
  const seek=player.getByRole('slider',{name:'Seek',exact:true});
  await seek.fill('15');
  await page.waitForFunction(()=>Math.abs(document.querySelector('.player video').currentTime-15)<.5);
  await transport.getByRole('button',{name:'Rewind 10 seconds'}).click();
  await page.waitForFunction(()=>Math.abs(document.querySelector('.player video').currentTime-5)<.5);
  check(true,label+' rewind moves back ten seconds');
  await transport.getByRole('button',{name:'Fast-forward 30 seconds'}).click();
  await page.waitForFunction(()=>Math.abs(document.querySelector('.player video').currentTime-35)<.5);
  check(true,label+' forward moves thirty seconds');
  await seek.fill('2');
  const volume=player.getByRole('button',{name:'Volume',exact:true});
  await volume.click();
  const dialog=page.getByRole('dialog',{name:'Volume',exact:true}),slider=dialog.getByRole('slider',{name:'Volume',exact:true});
  await slider.fill('0.6');
  await page.waitForFunction(()=>Math.abs(document.querySelector('.player video').volume-.6)<.01);
  check(await dialog.getByRole('status',{name:'Volume level'}).textContent()==='60',label+' volume popover shows the selected percentage');
  const time=await video.evaluate(element=>element.currentTime);
  await slider.focus();await page.keyboard.press('ArrowRight');
  check(Math.abs(await video.evaluate(element=>element.currentTime)-time)<.1,label+' volume arrow keys never seek the video');
  await dialog.getByRole('button',{name:'Mute',exact:true}).click();
  check(await video.evaluate(element=>element.muted),label+' popup mute affects actual playback');
  await dialog.getByRole('button',{name:'Unmute',exact:true}).click();
  await page.keyboard.press('Escape');
  await dialog.waitFor({state:'hidden'});
  check(await volume.evaluate(element=>document.activeElement===element),label+' closing volume restores trigger focus');
  await openPlaybackSetting(page,'Playback speed');
  await page.getByRole('menuitemradio',{name:'1.5×',exact:true}).click();
  check(await video.evaluate(element=>element.playbackRate===1.5&&element.preservesPitch&&element.paused),label+' speed changes without resuming a paused video');
  await openPlaybackSetting(page,'Audio');
  await page.getByRole('menu',{name:'Audio',exact:true}).getByRole('menuitemradio').nth(1).click();
  await page.waitForFunction(()=>{const audio=document.querySelector('.player audio');return audio.currentSrc&&audio.readyState>=2;});
  check(await video.evaluate(element=>element.playbackRate===1.5)&&await player.locator('audio').evaluate(element=>element.playbackRate===1.5&&element.preservesPitch),label+' replacement audio keeps the selected speed and pitch');
  await openPlaybackSetting(page,'Quality');
  await page.getByRole('menuitemradio',{name:/^480p/}).click();
  await page.waitForFunction(npm=>{const video=document.querySelector('.player video');return video.readyState>=2&&(npm?Math.min(video.videoWidth,video.videoHeight):video.videoHeight)===480;},label.startsWith('npm '));
  check(await video.evaluate(element=>element.playbackRate===1.5&&element.paused),label+' quality changes retain speed and pause');
  await page.reload();
  await video.waitFor();
  await page.waitForFunction(()=>document.querySelector('.player video')?.readyState>=2);
  check(await video.evaluate(element=>element.playbackRate===1.5),label+' speed survives a document reload');
  await player.getByRole('button',{name:'Pause',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.player video').paused);
  await openPlaybackSetting(page,'Playback speed');
  check(await page.getByRole('menuitemradio',{name:'1.5×',exact:true}).getAttribute('aria-checked')==='true',label+' stored speed is selected in Settings');
  await page.getByRole('menuitemradio',{name:'Normal (1×)',exact:true}).click();
  await openPlaybackSetting(page,'Quality');
  await page.getByRole('menuitemradio',{name:/^Original Quality/}).click();
  await openPlaybackSetting(page,'Audio');
  await page.getByRole('menu',{name:'Audio',exact:true}).getByRole('menuitemradio').first().click();
  await page.waitForFunction(()=>!document.querySelector('.player audio').getAttribute('src'));
  const more=player.getByRole('button',{name:'Playback settings',exact:true});
  await more.click();
  const menu=page.getByRole('menu',{name:'Settings',exact:true});
  check(await menu.getByRole('menuitem',{name:/Picture in Picture/}).count()===0,label+' PiP is outside Settings');
  if(await video.evaluate(element=>document.pictureInPictureEnabled))check(await player.getByRole('button',{name:'Picture in Picture',exact:true}).count()===1,label+' dedicated PiP button is visible');
  await page.keyboard.press('Escape');
  await seek.fill('1');
  await page.emulateMedia({reducedMotion:'no-preference'});
  await more.click();
  check(await menu.getAttribute('data-animate')==='true'&&await menu.evaluate(element=>getComputedStyle(element).transitionProperty.includes('opacity')),label+' pointer Settings animates');
  await menu.getByRole('menuitem',{name:'Repeat',exact:true}).click();
  const repeat=page.getByRole('menu',{name:'Repeat',exact:true});
  await repeat.evaluate(async element=>{
    await Promise.all(element.getAnimations({subtree:true}).map(animation=>animation.finished.catch(()=>{})));
  });
  const spacing=await repeat.evaluate(element=>({
    gap:element.querySelector('.playback-track-list button').getBoundingClientRect().top-element.querySelector('.playback-menu-heading').getBoundingClientRect().bottom,
    padding:parseFloat(getComputedStyle(element.querySelector('.playback-track-list')).paddingTop)
  }));
  check(spacing.gap>=7.9&&spacing.padding>=8,label+' submenu options are separated from the heading divider');
  check(await repeat.locator('.playback-menu-page').evaluate(element=>getComputedStyle(element).transitionProperty.includes('opacity')),label+' submenu pages have a fade transition');
  await page.keyboard.press('Escape');await page.keyboard.press('Escape');
  await more.focus();await page.keyboard.press('Enter');
  check(await menu.getAttribute('data-animate')==='false',label+' keyboard opens Settings immediately');
  await page.keyboard.press('Escape');
  if(await video.evaluate(element=>element.paused))await transport.getByRole('button',{name:'Play',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('.player video').paused);
  await more.click();await page.mouse.move(1,1);await page.waitForTimeout(2700);
  check(await player.evaluate(element=>element.classList.contains('controls-visible')),label+' open Settings keeps controls visible');
  await page.keyboard.press('Escape');
  await video.click({force:true}); // Click toggles pause; put the player back in its playing state below.
  if(await video.evaluate(element=>element.paused))await transport.getByRole('button',{name:'Play',exact:true}).click();
  await page.mouse.move(1,1);await page.evaluate(()=>document.activeElement?.blur());
  await page.waitForFunction(()=>!document.querySelector('.player').classList.contains('controls-visible'));
  const movement=await player.locator('.player-controls').evaluate(element=>({transform:getComputedStyle(element).transform,transition:getComputedStyle(element).transitionProperty}));
  check(movement.transition.includes('transform')&&movement.transform!=='none',label+' inactive controls fade downwards');
  await player.focus();await video.evaluate(element=>element.pause());
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.screenshot({path:join(artifacts,label.replace(/ /g,'-')+'-transport.png')});
}
